# --------------------------------------------------
# 1. แสดงเมนูและราคา (เครื่องดื่ม 7 รายการ)
# --------------------------------------------------
print("=== ร้าน Indy cafe ===")
print("1. ชาไทยเย็น (35 บาท)")
print("2. กาแฟเอสเพรสโซเย็น (45 บาท)")
print("3. ชาเขียวมัทฉะ (50 บาท)")
print("4. โกโก้เย็น (40 บาท)")
print("5. นมสดคาราเมล (45 บาท)")
print("6. ชามะนาว (35 บาท)")
print("7. นมเผือก (35 บาท)")
print("-----------------------------------")

# --------------------------------------------------
# 2. รับจำนวนแก้วจากผู้ใช้ (ใส่ 0 ถ้าไม่รับ)
# --------------------------------------------------
num1 = int(input("รับ ชาไทยเย็น กี่แก้ว: "))
num2 = int(input("รับ กาแฟเอสเพรสโซเย็น กี่แก้ว: "))
num3 = int(input("รับ ชาเขียวมัทฉะ กี่แก้ว: "))
num4 = int(input("รับ โกโก้เย็น กี่แก้ว: "))
num5 = int(input("รับ นมสดคาราเมล กี่แก้ว: "))
num6 = int(input("รับ ชามะนาว กี่แก้ว: "))
num7 = int(input("รับ นมเผือก กี่แก้ว: "))

# --------------------------------------------------
# 3. คำนวณราคารวม
# --------------------------------------------------
total = (num1 * 35) + (num2 * 45) + (num3 * 50) + (num4 * 40) + (num5 * 45) + (num6 * 35) + (num7 * 35)
print(f"\nราคารวมทั้งหมด: {total} บาท")

# --------------------------------------------------
# 4. คำนวณส่วนลดตามเงื่อนไข (If-Else)
# --------------------------------------------------
discount = 0

# เงื่อนไขที่ 1: ซื้อครบ 300 บาท ลด 10%
if total >= 300:
    discount = discount + (total * 0.10)
    print("-> ได้รับส่วนลดซื้อครบ 300 บาท (ลด 10%)")

# เงื่อนไขที่ 2: มีบัตรสมาชิก ลดเพิ่ม 50 บาท
is_member = input("มีบัตรสมาชิกหรือไม่? (พิมพ์ y หรือ n): ")
if is_member == "y":
    discount = discount + 50
    print("-> ได้รับส่วนลดบัตรสมาชิก 50 บาท")

# คำนวณยอดเงินที่ต้องจ่ายจริง
pay_amount = total - discount
print(f"ส่วนลดรวม: {discount} บาท")
print(f"ยอดเงินที่ต้องจ่ายจริง: {pay_amount} บาท")

# --------------------------------------------------
# 5. รับเงินและคำนวณเงินทอน
# --------------------------------------------------
cash = float(input("\nรับเงินจากลูกค้า (บาท): "))

if cash >= pay_amount:
    change = cash - pay_amount
    print(f"เงินทอน: {change} บาท")
    print("=== ขอบคุณที่ใช้บริการ ===")
else:
    print("จำนวนเงินไม่พอชำระ!")
